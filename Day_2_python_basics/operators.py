a=10
b=3

print("Arithematic Operators:")
print("Addition:",a+b)
print("Substraction:",a-b)
print("Multiplication:",a*b)
print("Division:",a/b)
print("Modulus:",a%b)
print("\nComparison Operators:")
print("a is greater than b:",a>b)
print("a is equal to b:",a==b)
print("b is greater than a:",a<b)
print("a is not equal to b:",a!=b)
print("\nLogical Operators:")
print("a is greater than 5 and b is less than 5:")
print("Using [and] operator:",a>5 and b<5)
print("Using [or] operator:",a>5 or b>5)
print("Using [not] operator:",not(a>5 and b<5))
print("\nMembership Operators:")
fruits=["Apple","Banana","Mango"]
